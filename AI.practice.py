import streamlit as st
from openai import OpenAI
import re

# ==========================================
# 페이지 설정
# ==========================================

st.set_page_config(
    page_title="AI 조언 연습장",
    page_icon="💗",
    layout="centered"
)

# ==========================================
# OpenAI API
# ==========================================

try:
    api_key = st.secrets["OPENAI_API_KEY"]
except KeyError:
    st.error("🔑 OPENAI_API_KEY가 설정되지 않았어요.")
    st.info(
        "Streamlit Cloud → Settings → Secrets에서 "
        "OPENAI_API_KEY를 입력해주세요."
    )
    st.stop()

client = OpenAI(api_key=api_key)

# ==========================================
# 캐릭터
# ==========================================

CHARACTERS = {
    "sad": {
        "face": "🥺",
        "name": "토닥이",
        "message": "많이 힘들었구나. 괜찮아, 천천히 이야기해도 돼."
    },

    "angry": {
        "face": "😤",
        "name": "씩씩이",
        "message": "그건 화날 만해. 네 마음부터 한번 정리해보자."
    },

    "anxious": {
        "face": "🥹",
        "name": "콩닥이",
        "message": "걱정이 많았구나. 하나씩 천천히 생각해보자."
    },

    "tired": {
        "face": "😮‍💨",
        "name": "몽글이",
        "message": "많이 지쳤겠다. 잠깐 쉬어가도 괜찮아."
    },

    "happy": {
        "face": "😊",
        "name": "방긋이",
        "message": "좋은 일이 있었구나! 그 기분 오래 간직하자."
    },

    "critical": {
        "face": "🗿",
        "name": "팩트봇",
        "message": "일단 감정은 잠깐 내려놓고, 현실을 제대로 보자."
    }
}

# ==========================================
# 제목
# ==========================================

st.title("💗 AI 조언 연습장")
st.caption("고민을 적어주면 AI가 읽고, 판단하고, 맞춤 조언을 해줘요!")

st.divider()

# ==========================================
# 고민 입력
# ==========================================

problem = st.text_area(
    "💭 무슨 고민이 있나요?",
    placeholder="예: 친구랑 싸웠는데 내가 먼저 연락해야 할지 모르겠어.",
    height=170
)

# ==========================================
# 조언 스타일
# ==========================================

style = st.selectbox(
    "🌷 어떤 조언을 받고 싶나요?",
    [
        "따뜻하고 공감하는 조언",
        "친구처럼 편한 조언",
        "현실적이고 솔직한 조언",
        "논리적으로 정리해주는 조언",
        "짧고 핵심적인 조언",
        "🗡️ 비판적이고 독한 조언"
    ]
)

# ==========================================
# 조언 받기
# ==========================================

if st.button("💌 조언 받기", use_container_width=True):

    if not problem.strip():
        st.warning("고민을 먼저 적어주세요! 🥺")
        st.stop()

    # --------------------------------------
    # AI에게 전달할 시스템 프롬프트
    # --------------------------------------

    system_prompt = f"""
너는 사용자의 고민을 읽고 상황에 맞는 조언을 해주는 AI다.

사용자가 입력한 내용을 단순한 키워드로 판단하지 말고,
전체적인 상황과 감정을 읽고 맥락에 맞는 답변을 만들어라.

현재 사용자가 원하는 조언 스타일:
{style}

========================
조언 스타일별 규칙
========================

[따뜻하고 공감하는 조언]
사용자의 감정을 충분히 이해해주고,
부담스럽지 않게 현실적인 해결 방법을 제시한다.

[친구처럼 편한 조언]
친한 친구가 이야기하는 것처럼 자연스럽고 편하게 말한다.
너무 딱딱하거나 상담사처럼 말하지 않는다.

[현실적이고 솔직한 조언]
감정적인 위로보다 실제 상황에서 도움이 되는 방법을 우선한다.
필요하면 불편한 사실도 솔직하게 이야기한다.

[논리적으로 정리해주는 조언]
상황의 원인과 문제점을 정리하고,
선택 가능한 행동과 각각의 결과를 설명한다.

[짧고 핵심적인 조언]
불필요한 설명을 줄이고 핵심적인 조언만 전달한다.

[🗡️ 비판적이고 독한 조언]
무조건 사용자의 편을 들지 않는다.
사용자의 잘못된 행동, 회피, 자기합리화, 모순이 있다면 직접 지적한다.
돌려 말하지 않고 직설적으로 말한다.

예:
"그건 네가 잘못한 부분이 있어."
"지금 네가 문제를 해결하는 대신 피하고 있는 것 같아."
"상대방이 알아서 눈치채길 기다리는 건 해결책이 아니야."

하지만 다음은 절대 하지 않는다.
- 사용자의 인격이나 존재 자체를 공격하지 않는다.
- 외모나 신체를 비하하지 않는다.
- 욕설로 사용자를 모욕하지 않는다.
- 상처를 주는 것 자체를 목적으로 하지 않는다.

독한 조언의 목적은 사용자를 공격하는 것이 아니라
문제를 직면하게 하고 행동을 바꾸도록 돕는 것이다.

========================
감정 판단
========================

사용자의 고민을 읽고 가장 적절한 감정을 하나 선택한다.

가능한 감정:
sad
angry
anxious
tired
happy

========================
답변 형식
========================

반드시 아래 형식을 지켜라.

MOOD: 감정 하나

ADVICE:
사용자에게 해줄 조언

========================
추가 규칙
========================

- 반드시 한국어로 답한다.
- 사용자의 고민에 실제로 맞는 답변을 한다.
- 고정된 문장을 반복하지 않는다.
- 고민 내용에 따라 매번 새로운 조언을 만든다.
- 사용자의 감정과 상황을 구분해서 판단한다.
- 무조건적인 위로를 하지 않는다.
- 필요한 경우 사용자의 잘못도 지적한다.
- 너무 장황하지 않게 작성한다.
"""

    user_prompt = f"""
다음은 사용자가 직접 작성한 고민이다.

[사용자의 고민]
{problem}

위 내용을 충분히 읽고 상황에 맞는 조언을 만들어라.
"""

    # ======================================
    # API 호출
    # ======================================

    with st.spinner("🐰 고민을 읽고 있어요..."):

        try:

            response = client.responses.create(
                model="gpt-5.4-nano",
                instructions=system_prompt,
                input=user_prompt
            )

            result = response.output_text.strip()

            # ==================================
            # 감정 추출
            # ==================================

            mood_match = re.search(
                r"MOOD\s*:\s*(sad|angry|anxious|tired|happy)",
                result,
                re.IGNORECASE
            )

            if mood_match:
                mood = mood_match.group(1).lower()
            else:
                mood = "sad"

            # ==================================
            # 조언 추출
            # ==================================

            advice_match = re.search(
                r"ADVICE\s*:\s*(.*)",
                result,
                re.IGNORECASE | re.DOTALL
            )

            if advice_match:
                advice = advice_match.group(1).strip()
            else:
                advice = result

            # ==================================
            # 독한 조언이면 캐릭터 변경
            # ==================================

            if style == "🗡️ 비판적이고 독한 조언":
                character = CHARACTERS["critical"]
            else:
                character = CHARACTERS[mood]

            # ==================================
            # 결과 출력
            # ==================================

            st.divider()

            # 캐릭터
            st.markdown(
                "<div style='text-align:center;'>"
                f"<div style='font-size:90px;'>{character['face']}</div>"
                f"<h2>{character['name']}</h2>"
                "</div>",
                unsafe_allow_html=True
            )

            st.write(
                f"**{character['message']}**"
            )

            st.divider()

            # 조언
            st.subheader("💬 내가 해줄 말")

            st.write(advice)

            st.divider()

            # 감정 상태는 작은 글씨로 표시
            mood_names = {
                "sad": "🥺 슬픔",
                "angry": "😤 분노",
                "anxious": "🥹 불안",
                "tired": "😮‍💨 피로",
                "happy": "😊 긍정"
            }

            st.caption(
                f"AI가 판단한 현재 감정: {mood_names.get(mood, '🙂 기타')}"
            )

        except Exception as e:

            st.error("😵 AI에게 조언을 요청하는 중 문제가 발생했어요.")

            st.caption(
                "API Key 또는 모델 설정을 확인해주세요."
            )

            st.code(str(e))
